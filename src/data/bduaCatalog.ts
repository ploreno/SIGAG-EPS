export function routeAuxiliarOperativo(
  dpto: string,
  glosa: string,
  estado: 'LISTO' | 'PENDIENTE' | 'REVISIÓN'
): string {
  if (estado === 'LISTO') return 'Motor Algorítmico';
  if (glosa === 'GN0258' || glosa === 'GN0297') return 'Auxiliar Sisbén IV';
  if (glosa === 'GN0302') return 'Auxiliar Contributivo PILA';
  if (dpto === '66') return 'Auxiliar Risaralda (66)';
  return 'Auxiliar Valle (76)';
}

